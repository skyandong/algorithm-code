package dynamicprogramming

// climbStairs 解决「爬楼梯」问题：每次可以爬 1 或 2 个台阶，爬到第 n 阶有多少种方法。
// https://leetcode.cn/problems/climbing-stairs/description/
//
// 【题意】n 阶楼梯，每步走 1 或 2，求到达第 n 阶的方案数。
//
// 【算法选择：为什么是动态规划而非递归 / 矩阵快速幂】
//  1. 最朴素的递归 f(n) = f(n-1) + f(n-2) 存在大量重复子问题（同一 f(k) 被反复计算），
//     时间复杂度 O(2^n)，n=45 时根本跑不完。这是教科书级的「重叠子问题」信号，直接上 DP。
//  2. 标准的 f(n) = f(n-1) + f(n-2) 即斐波那契递推，状态仅依赖前两项，因此无需整张 dp 数组，
//     用两个滚动变量即可，空间降到 O(1)。这里就是采用滚动变量写法。
//  3. 理论上还有矩阵快速幂 O(log n) 解法，但对 n<=45 的数据范围是杀鸡用牛刀，反而增加代码复杂度，
//     面试中除非被明确追问，否则不写。这里 O(n) 已是该数据规模下的合理下界。
//
// 【时间复杂度】O(n)，单次循环。
// 【空间复杂度】O(1)，仅两个变量滚动，已是该解法的理论下界。
//
// 【状态定义与转移】
//   设 f(k) 表示爬到第 k 阶的方案数：
//     f(0) = 1  // 在地面（第 0 阶）算作 1 种「已到达」状态，这是为了转移自洽而设的语义
//     f(1) = 1  // 到第 1 阶只有「走一步」1 种方法
//     f(k) = f(k-1) + f(k-2)  // 最后一步要么从 k-1 走 1，要么从 k-2 走 2，两类不重叠
//
// 【易错点：f(0) 为什么是 1 而不是 0】
//   很多人直觉认为「第 0 阶方案数 = 0」（因为没爬），但这会让转移不自洽：
//   若 f(0)=0，则 f(2)=f(1)+f(0)=1+0=1，而实际上到第 2 阶有「1+1」「2」共 2 种方法。
//   正确语义是：f(0) 表示「从地面出发、不消耗步数即处于第 0 阶」这一唯一状态，故为 1。
//   这是组合计数 DP 的通用约定：空集 / 起点方案数记 1，保证边界转移成立。
func climbStairs(n int) int {
	// 初始化：a 对应 f(0)=1，b 对应 f(1)=1。
	// 注意这里用「双指针」而非 dp 数组，正是利用了状态只依赖前两项的特性。
	// 【坑】不要写成 a, b := 0, 1，那是斐波那契数列 F(0)=0 的约定；
	//      本题的 f(0)=1（爬楼梯方案数），两者语义不同，写错会让 n=2 等用例直接挂掉。
	a, b := 1, 1 // a=f(0), b=f(1)
	// 从第 2 阶开始递推：i==0 和 i==1 已由初值给出，循环覆盖 i=2..n。
	// 【边界】i<=n 而非 i<n：第 n 阶也要算进来，少一次循环会少推一阶导致返回错误值。
	for i := 2; i <= n; i++ {
		// 滚动更新：新 b = 旧 a + 旧 b（即 f(i)=f(i-2)+f(i-1)），新 a = 旧 b（即 f(i-1)）。
		// Go 的多重赋值是「先求值再赋值」，因此 a, b = b, a+b 等价于 tmp := a+b; a=b; b=tmp，
		// 不会出现「a 先被改写导致 b 算错」的顺序问题。这是用 Go 写滚动 DP 的天然优势，
		// 换成 C/Java 的 a=b; b=a+b; 就会踩坑，需要引入临时变量。
		// 【方向】始终向后滚动（a 始终代表当前的前一项），不要尝试「从 n 倒推到 0」——
		//        自底向上递推才符合无后效性，且能复用前序已计算的状态。
		a, b = b, a+b
	}
	// 循环结束时 b == f(n)。当 n==1 时循环不执行，直接返回初值 b=1，正好是 f(1)，正确。
	// 当 n==0 时同理返回 b=1（即 f(0)），LeetCode 约束 n>=1，但即便 n=0 也能给出语义正确的答案。
	return b
}
