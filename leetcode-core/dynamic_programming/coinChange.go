package dynamicprogramming

// 零钱兑换
// https://leetcode.cn/problems/coin-change/description/
//
// 题意:给定不同面额的硬币 coins 和一个总金额 amount,求凑成该金额所需的最少硬币数。
// 每种硬币数量不限(完全背包模型)。若无法凑出,返回 -1。
//
// 为什么选 DP 而不是贪心 / 记忆化搜索:
//   - 贪心(每次尽量取最大面额)会错。反例 coins={1,3,4},amount=6:
//     贪心得 4+1+1=3 枚,而最优解是 3+3=2 枚。贪心只在硬币面额满足"整除/Canonical"性质时才正确,
//     一般情况下不成立,所以必须用全局 DP。
//   - 记忆化搜索(自顶向下 DFS + memo)思路等价、复杂度相同,但递归栈开销更大、
//     且边界判断不如递推直观。这里选自底向上的递推,常数因子更小、空间也可复用单数组。
//
// 状态定义:dp[i] = 凑出金额 i 所需的最少硬币数。
// 转移方程:dp[i] = min(dp[i-c] + 1) 对所有 c <= i。即"最后一步"选了一枚面额 c,
//   剩下的金额 i-c 已经是最优解,加这一枚即可。这正是无后效性的体现:
//   子问题 i-c 的最优解不依赖于"如何到达 i",所以可以安全复用。
//
// 为什么是"完全背包"而非"0-1 背包":每种硬币可无限次使用,所以内层正序遍历金额 i,
//   同一枚面额在同一轮里可以被多次"消费"。若改成 0-1 背包(每枚只能用一次),
//   就要把外层循环换成"物品"且内层逆序。本题硬币无限,正序即可。
//
// 时间复杂度:O(amount * len(coins)),即状态数 amount 乘以每个状态的转移数。
//   这是该问题的理论下界(每个子问题至少要看一遍所有硬币才能确定最小值)。
// 空间复杂度:O(amount),用一维数组做滚动,已是最优空间。
func coinChange(coins []int, amount int) int {
	// dp[i] 表示凑出金额 i 的最少硬币数;数组长度 amount+1,下标 0..amount。
	dp := make([]int, amount+1)
	for i := range dp {
		// 【初始化哨兵值】这里用 amount+1 而不是 math.MaxInt,是个关键细节:
		//   转移时会出现 dp[i-c]+1,若哨兵是 MaxInt,+1 会溢出成负数,导致 min 取到错误的小值,
		//   最终返回一个荒谬的负数答案。amount+1 在语义上"不可能被超越":
		//   即便全部用面额 1 的硬币,也最多用 amount 枚,任何合法解的硬币数都 <= amount。
		//   因此 amount+1 充当"无穷大"既安全又无溢出风险。判断无解时只需 dp[amount] > amount。
		dp[i] = amount + 1
	}
	// 【base case】金额为 0 时需要 0 枚硬币。这是递推的起点,必须显式置 0,
	//   否则 dp[0] 仍是哨兵 amount+1,后续所有依赖 dp[0] 的转移都会错。
	dp[0] = 0

	// 外层按金额从小到大递推:保证计算 dp[i] 时,所有更小的 dp[i-c] 都已就绪。
	for i := 1; i <= amount; i++ {
		// 内层遍历每种硬币,尝试把它作为"最后一步"的那一枚。
		// 顺序无关:这里是对 coin 取 min,任意顺序都能得到相同结果。
		for _, c := range coins {
			// c <= i:金额 i 至少要 ≥ c 才能用这枚硬币,否则 i-c 为负越界。
			// dp[i-c]+1 < dp[i]:取更小值。用哨兵初始化的好处之一就是这里
			//   即使 dp[i-c] 还是"不可达"(哨兵),+1 后仍 = amount+2,不会污染答案,
			//   只是不会被 min 选中而已。
			if c <= i && dp[i-c]+1 < dp[i] {
				dp[i] = dp[i-c] + 1
			}
		}
	}

	// 【无解判定】若 dp[amount] 仍 > amount,说明没有任何组合能凑出该金额(哨兵未被更新)。
	//   注意用 > 而不是 !=:哨兵是 amount+1,但 amount=0 时哨兵也是 1,而 dp[0] 已被置 0,
	//   不会误判;用 > amount 比 == amount+1 更鲁棒,不依赖哨兵的具体取值。
	if dp[amount] > amount {
		return -1
	}
	return dp[amount]
}
