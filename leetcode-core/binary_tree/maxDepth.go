package binarytree

// 二叉树的最大深度
// https://leetcode.cn/problems/maximum-depth-of-binary-tree/description/
//
// 题意: 给定一棵二叉树的根节点 root, 返回它的最大深度。
// 最大深度是指从根节点到最远叶子节点的最长路径上的节点数(注意是"节点数"而非"边数",
// 所以空树深度为 0, 单节点树深度为 1, 这是和"高度/边数"定义的关键差别)。
//
// 算法选择: 递归 DFS(后序)。
// 为什么选后序递归而不是其他写法?
//   1. 深度的本质是一个"自底向上"的聚合信息——子树的最大深度 + 当前节点这 1 层。
//      后序(先算左右子树, 再合并到当前节点)天然契合这种"先依赖子问题、再合成父问题"
//      的结构, 代码最短、最不容易写错。
//   2. 对比 BFS(层序): 层序也能求深度(数有多少层即可), 但需要显式维护队列和
//      按层切分, 代码更长; BFS 在"求最小深度"时优势明显(可提前终止), 但求
//      "最大深度"必须遍历到最后一层, 提前终止不了, 所以 DFS 更简洁。
//   3. 对比自顶向下(前序 + 全局变量): 也可以用一个外部变量记录"当前走到第几层"
//      并在叶子处更新最大值, 但要引入额外状态, 且递归参数多一层; 后序写法把状态
//      封装在返回值里, 无副作用, 更函数式、更不容易出 bug。
//
// 时间复杂度: O(n), 每个节点恰好访问一次, 这是理论下界——求最大深度必须至少
// 看一眼每个节点(否则最坏情况下最深的叶子可能被漏掉), 所以 O(n) 已是最优。
// 空间复杂度: O(h), h 为树高, 即递归调用栈深度。
//   - 平衡树: h = O(log n), 栈空间 O(log n)。
//   - 退化为链(左斜/右斜): h = O(n), 栈空间 O(n)。
//   【面试常追问坑点】最坏空间不是 O(log n) 而是 O(n)。如果面试官追问"能否保证
//   O(log n) 空间", 答案是不能仅靠改写递归实现——必须先保证树本身平衡(如 AVL/
//   红黑树), 算法本身无法把斜树的空间压下来。另外, 工程上极端深的递归会触发栈溢出,
//   这时才需要考虑改成迭代(Morris 遍历或显式栈), 但面试默认接受递归写法。
func maxDepth(root *TreeNode) int {
	// 递归终止条件: 空节点返回 0。
	// 注意返回的是 0 而不是 -1: 因为深度按"节点数"计, 空子树对父节点的贡献是 0 层。
	// 若题目改为按"边数"计深度, 这里才需要返回 -1(让 1 + max(...) 抵消掉叶子那层多算的边)。
	// 【易错点】把 0 写成 -1 或 1 是这类题最常见的一类 off-by-one, 直接导致整体深度差 1。
	if root == nil {
		return 0
	}
	// 1 是当前节点这一层; 左右子树取较大者即为"更深的那个分支"。
	// 为什么是 max 而非 min/加和:
	//   - max: 最深路径只会沿左右某一个分支走到底, 不是两边都走, 所以取较大者。
	//   - 若用 min 会变成"最小深度"(且语义还不完全等价), 答案错误。
	//   - 若把左右相加则是"直径/路径和"类问题的做法, 与"深度"无关。
	// 【面试追问】如何改造求"最小深度"? 不能直接把 max 换成 min——空子树返回 0 会让
	//   单边缺失的节点误判为深度 1。最小深度需要额外判断: 当某一边子树为空时,
	//   只能取另一边的深度(详见 minDepth 题), 这是和最大深度最大的坑点差异。
	return 1 + max(maxDepth(root.Left), maxDepth(root.Right))
}
