package binarytree

// 二叉树的中序遍历
// https://leetcode.cn/problems/binary-tree-inorder-traversal/
//
// 题意：按"左子树 -> 根 -> 右子树"的顺序访问二叉树的所有节点，返回节点值序列。
// 对于二叉搜索树（BST），中序遍历的结果恰好是升序的，这是中序遍历最重要的性质。
//
// 算法选择理由（递归 vs 迭代 vs Morris）：
//   1. 递归写法（本文件采用）：最直观、最不容易写错，是面试时首选的"先保命"方案。
//      递归天然利用函数调用栈来保存"回到上一层"的返回点，代码与"左-根-右"的定义一一对应。
//   2. 迭代写法（用显式栈）：当题目要求 O(1) 额外空间之外的常数因子，或面试官追问
//      "能不能不用递归"时再写。本质是把递归调用栈手动展开成一个 []*TreeNode 栈。
//   3. Morris 遍历：能做到 O(1) 额外空间（不含输出），但会临时修改树结构（线索化），
//      实现复杂、易错，仅在明确要求 O(1) 空间时才考虑。
// 这里先用递归，把"做对"放在第一位；面试时口头能讲出迭代/Morris 即可加分。
//
// 时间复杂度：O(n)，每个节点访问且仅访问一次。这已经是理论下界——要输出全部 n 个节点值，
// 必须至少访问每个节点一次，O(n) 不可继续优化。
// 空间复杂度：O(h)，h 为树高。这是递归调用栈的深度（不是结果数组的大小，结果数组是
//   输出本身，通常不计入额外空间）。最坏情况（退化为链表）h=n → O(n)；
//   平衡树 h=log n → O(log n)。注意：如果面试官把输出数组也算进空间，则是 O(n)。
func inorderTraversal(root *TreeNode) []int {
	// 这里用 make([]int, 0) 而非 var ret []int，是为了避免返回 nil。
	// LeetCode 对返回 nil vs []int{} 不敏感，但在本地测试/实际工程中，
	// 调用方拿到一个长度为 0 的非 nil 切片更安全（避免 nil 解引用、JSON 序列化为 null 等）。
	ret := make([]int, 0)
	inorderTraversalW(&ret, root)
	return ret
}

// inorderTraversalW 是递归主体。
// 之所以把结果切片以 *[]int 指针传入，而不是返回 []int 再拼接，有两个原因：
//  1. 若每个递归层都返回一个新切片再 append 拼接，会产生大量临时切片，
//     时间从 O(n) 退化到 O(n^2)（每次 append 拷贝），且 GC 压力大。
//  2. 用 *[]int 共享同一个底层数组，append 只发生在一处，扩容次数最少，
//     这是把 O(n) 时间坐实的关键。
// 【易错点】传入的是 *[]int（指向切片头的指针），而不是 **[]int 或 []int。
//   注意：切片本身已经是引用语义（底层数组指针），即使按值传 []int，append 在
//   调用方也看不到扩容后的新切片头——这正是必须传 *[]int 的根本原因：
//   append 可能触发扩容并产生新的切片头，必须让调用方拿到新的切片头。
//   这是 Go 切片语义最容易踩的坑之一。
func inorderTraversalW(ret *[]int, root *TreeNode) {
	if root == nil {
		return
	}
	// 顺序必须是"左 -> 根 -> 右"，与中序定义严格对应。
	// 下面三行的顺序绝对不能换：先递归左子树，再访问当前节点，再递归右子树。
	// 【面试追问】为什么不能把 *ret = append(...) 放在最前面？
	//   放最前面就变成"前序遍历"（根-左-右）了；放在最后则是"后序"（左-右-根）。
	//   三种遍历的差别仅在于"访问当前节点"这一行在三行中的位置。
	inorderTraversalW(ret, root.Left)
	*ret = append(*ret, root.Val)
	inorderTraversalW(ret, root.Right)
}
