package dynamicprogramming

// 最长回文子串
// https://leetcode.cn/problems/longest-palindromic-substring/description/
//
// 题意: 给定字符串 s,返回其中最长的回文子串(连续)。例如 "babad" -> "bab"(或 "aba",任一即可)。
//
// 算法选择——为什么用「中心扩展」而不是 DP 或 Manacher:
//
//  1. 区间 DP: 设 dp[i][j] 表示 s[i..j] 是否为回文,转移为 dp[i][j] = (s[i]==s[j]) && (j-i<2 || dp[i+1][j-1])。
//     时间 O(n^2)、空间 O(n^2)。能做对,但有两个硬伤:
//     - 空间 O(n^2),n=1000 时 dp 表 ~4MB,且必须按「长度」或「i 倒序」枚举,顺序极易写反(见下)。
//     - 只是「判断」回文,不天然导向「中心对称」的直觉。
//
//  2. 中心扩展: 回文关于中心对称,从每个中心向两侧尽量扩展即可。
//     时间 O(n^2)(共 2n-1 个中心,每个最多扩展 n/2 步)、空间 O(1)。
//     【为什么选它】常数小、空间最优、代码短、不易写错;面试中除非题目要求输出回文数量,
//     否则中心扩展是默认首选。空间 O(1) 是相对 DP 的关键优势。
//
//  3. Manacher: 时间 O(n)、空间 O(n)。理论最优,但实现复杂、常数大、边界多,
//     面试中除非明确要求线性,否则不划算——写错概率远大于中心扩展。可作为追问时的「我会但不必上」的答案。
//
// 【关键认知】中心数是 2n-1 而不是 n:回文中心可以是「一个字符」(奇数长度,如 "aba"),
// 也可以是「两个字符之间的缝隙」(偶数长度,如 "abba")。n 个字符有 n 个字符中心 + (n-1) 个缝隙中心 = 2n-1。
// 本实现没有把缝隙显式编号,而是用 expand(i,i) 处理字符中心、expand(i,i+1) 处理缝隙中心,等价但更直观。
//
// 时间复杂度 O(n^2) 是否为下界: 不是,Manacher 可做到 O(n)。但中心扩展已是该写法下的最优枚举,
// 每个中心的扩展步数是「注定要做的比较次数」,无法再剪。
func longestPalindrome(s string) string {
	if len(s) <= 1 {
		// 【边界】空串直接返回空;单字符本身就是长度 1 的回文。提前返回也避免了下面 expand 越界的隐患。
		return s
	}

	// expand 从某个「中心」向两侧扩展,返回能扩展出的回文长度。
	// 闭包捕获外层 s,避免把 s 当参数到处传;闭包对只读 s 安全,不会被并发改写。
	//
	// 【为什么参数是 (left,right) 而不是单个 center】: 用一对指针同时表达两类中心——
	//   奇数中心传 (i,i),偶数中心传 (i,i+1)。统一成「两个指针从相邻或重合位置向外扩」这一种写法,
	//   避免奇/偶分写两套几乎重复的代码。
	expand := func(left, right int) int {
		for left >= 0 && right < len(s) && s[left] == s[right] {
			// 三个条件顺序无关紧要但都不能少:
			//  - left>=0:   防止左侧越界(下面 left-- 会到 -1)
			//  - right<len: 防止右侧越界(下面 right++ 会到 len)
			//  - s[left]==s[right]: 回文的必要条件;不等就停
			left--
			right++
		}
		// 【最易错的点:返回值怎么算】循环退出时,left/right 已停在「第一个不满足条件的中心外侧」。
		// 即退出后 s[left+1 .. right-1] 才是回文,长度 = (right-1) - (left+1) + 1 = right - left - 1。
		// 不能写成 right-left+1(那是把两端的非法字符也算进去了),也不能直接返回 left/right 本身。
		// 举例: s="aba",expand(1,1) 退出时 left=-1,right=3,长度 = 3-(-1)-1 = 3,正确。
		return right - left - 1
	}

	// begin 记录当前最长回文的起始下标,maxLen 记录其长度。
	// 【为什么不预初始化 maxLen=1】: expand 对每个中心都会至少返回 1(单字符自身回文),
	// 第一次循环必然命中 if l>maxLen(1>0),begin/maxLen 会被正确更新。所以 0 作为「哨兵」即可,
	// 预设成 1 反而要额外处理「空串」的特例,不如统一从 0 起步。
	begin, maxLen := 0, 0

	for i := 0; i < len(s); i++ {
		l1 := expand(i, i)   // 奇数长度: 中心是字符 s[i],可能得到 "x"、"xyx"、"xyz y zx"...
		l2 := expand(i, i+1) // 偶数长度: 中心是 s[i] 与 s[i+1] 之间的缝隙,可能得到 "xx"、"xyyx"...
		// 【为什么要两种都试】: 只试奇数会漏掉 "abba" 这类偶数回文(它的最长回文是 "bb"/"abba",
		// 没有任何单字符中心能扩展出偶数长度);只试偶数会漏掉 "aba"。两类中心覆盖的回文集合互补且不重叠。
		// 注意 expand(i,i+1) 在 i=len-1 时 right=len,循环条件 right<len 直接 false,返回 0,安全,无需特判。

		l := l1
		if l2 > l1 {
			l = l2
		} // 取两者较大者;不用 math.Max 是为了保持自包含、避免额外 import。
		// 等价于 l := max(l1, l2),Go 1.21+ 内置 max 亦可,但这里写成显式 if 不依赖版本。

		if l > maxLen {
			// 【由长度反推起始下标: 为什么是 i-(l-1)/2】
			// 以 i 为中心、长度 l 的回文,其左端点 = i - (l-1)/2。下面分类验证:
			//  - 奇数 l=2k+1: 来自 expand(i,i),中心就是 i,左端点 i-k = i-(l-1)/2。正确。
			//  - 偶数 l=2k:   来自 expand(i,i+1),实际对称中心在 i 与 i+1 之间,左端点 i-k+1。
			//    而 (l-1)/2 = (2k-1)/2,在 Go 里整数除法向下取整 = k-1,所以 i-((l-1)/2) = i-(k-1) = i-k+1。正确。
			// 【整除向下取整是公式成立的关键】: 这里依赖 Go 对正整数除法「向零截断」(等价于向下取整)。
			// 若语言用浮点或四舍五入会出错。偶数长度靠这一步「恰好」把中心缝隙折算到正确的左端点。
			// 也可写成 i - l/2 + 1,对偶数更直观,但奇数时要单独处理;统一用 (l-1)/2 省一个分支。
			begin = i - (l-1)/2
			maxLen = l
		}
	}
	// Go 的切片 s[begin:begin+maxLen] 是左闭右开,这里 begin+maxLen 必然 <= len(s):
	// 回文长度 l 是从真实扩展得到的,右端点 (begin+l-1) 在扩展过程中被 right<len 保护过,不会越界。
	return s[begin : begin+maxLen]
}
