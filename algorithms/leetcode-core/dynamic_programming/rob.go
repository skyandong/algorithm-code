package dynamicprogramming

// 打家劫舍
// https://leetcode.cn/problems/house-robber/description/
//
// 题意: 一排房屋, 每间含金额 nums[i]. 不能抢相邻的两间, 否则会报警.
//       求能抢到的最大总金额.
//
// 算法选择理由 (DP, 状态机模型):
//   - "不能相邻" 是一个带前缀依赖的约束, 天然适合 DP: 第 i 家的决策只取决于
//     "上一家有没有被抢", 与更早的历史无关 —— 满足最优子结构 + 无后效性.
//   - 定义 dp[i] = 考虑前 i+1 家 (下标 0..i) 能抢到的最大金额.
//     转移: dp[i] = max(dp[i-1], dp[i-2] + nums[i])
//       * 抢第 i 家: 那么第 i-1 家不能抢, 收益 = dp[i-2] + nums[i]
//       * 不抢第 i 家: 收益沿用 dp[i-1]
//   - 这里不选贪心 (如每步抢最大的可抢房): 贪心只看局部, 会错过 "放弃眼前小利、
//     换取后面更大组合" 的全局最优. 反例 [2,1,1,2]: 贪心先抢 2(下标0), 后面
//     只能抢下标3的2, 得 4; 但 dp 给出的最优也是 4 —— 看似相等; 换成
//     [2,3,2] 贪心得 3, dp 得 4, 贪心失效. 故必须 DP.
//
// 时间复杂度: O(n), 单次遍历. 这已是理论下界 —— 至少要把每间房看一遍才能
//   确定最优, 下界 Omega(n).
// 空间复杂度: O(1). 原始 dp 数组为 O(n), 但转移只需 dp[i-1] 和 dp[i-2],
//   用两个滚动变量即可, 无需保留全部历史.
//
// 初始化要点:
//   prev, curr := 0, 0
//   - 用 0 而不是负无穷: 金额都非负, "什么都没抢" 的合法收益是 0,
//     dp[i-1]、dp[i-2] 在边界外 (i<0) 时退化为 0, 数学上自洽.
//   - 这也天然处理了空数组 (循环不执行, 直接返回 0) 和单元素数组
//     (第一轮 prev=0,curr=0; 迭代后 curr=max(0, 0+nums[0])=nums[0]).
func rob(nums []int) int {
	prev, curr := 0, 0 // prev=dp[i-2], curr=dp[i-1]
	for _, x := range nums {
		// 抢这家(prev+x) 或 不抢这家(curr),取大
		//
		// 【易错点: 滚动变量的更新顺序】
		// 这里用 Go 的多重赋值 (tuple assignment):
		//   prev, curr = curr, max(curr, prev+x)
		// 右侧表达式会先整体求值, 再一次性赋值给左侧. 因此右侧的 prev 是
		// "更新前的 dp[i-2]", curr 是 "更新前的 dp[i-1]", 计算结果正确.
		//
		// 如果改成分号两句顺序赋值:
		//   prev = curr               // prev 先被改成 dp[i-1]
		//   curr = max(curr, prev+x)  // 这里 prev 已是 dp[i-1], 用错值!
		// 就会破坏依赖关系, 答案错误. 多重赋值能避免引入临时变量, 是惯用法.
		//
		// 另一种等价但更啰嗦的写法:
		//   next := max(curr, prev+x)
		//   prev = curr
		//   curr = next
		// 逻辑正确但多一个临时变量; 多重赋值让编译器帮你管临时变量.
		//
		// 【面试官常追问: 为什么是 prev+x 而不是 curr+x?】
		// 抢当前房 x 时, 前一间 (i-1) 必须不能抢, 所以只能接 dp[i-2]=prev,
		// 绝对不能接 dp[i-1]=curr. 用 curr+x 等价于允许抢相邻两间, 违反约束.
		prev, curr = curr, max(curr, prev+x)
	}
	return curr
}
