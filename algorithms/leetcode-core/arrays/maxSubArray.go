package arrays

// 最大子数组和
// https://leetcode.cn/problems/maximum-subarray/description/
//
// 题意: 在整数数组 nums 中找出一个连续子数组(至少含一个元素)，使其元素之和最大，返回该最大和。
//       注意"连续"二字——子数组必须是相邻的一段，不能跳着选; 区别于"子序列"(可不相邻, 那题会更简单)。
//
// 为什么选 Kadane 算法(动态规划)而不是其他解法:
//   1. 暴力 O(n^2): 枚举所有子数组起止端点再求和(O(n^3))或借助前缀和优化到 O(n^2)。
//      思路直观但面试官会立刻追问"能不能 O(n)?"，作为最终答案不够。
//   2. 分治 O(n log n): 把数组对半切，最大子数组和 = max(左半最大, 右半最大, 跨中点最大)。
//      跨中点的最大和 = 从 mid 向左延伸的最大前缀和 + 从 mid+1 向右延伸的最大前缀和。
//      能做但代码更长、常数更大，且仍不是理论最优。
//   3. Kadane O(n) O(1): 最优。核心是一个"局部最优"的状态定义，让全局最优在扫描中自然浮现。
//
// Kadane 的状态定义(WHY 这么定义):
//   令 cur = "以 nums[i] 结尾的"最大子数组和。这个"以 i 结尾"的约束是关键——
//   它把无约束的全局问题转成了有结构、可递推的局部问题:
//     要么把 nums[i] 接在以 nums[i-1] 结尾的最大子数组后面 (cur+nums[i])，
//     要么前面的累积是负贡献、干脆从 i 重新开始 (nums[i])。
//   取两者较大值即新的 cur。而全局答案 ans = max(所有位置的 cur)。
//   "前面的累积为负就丢弃"正是 Kadane 的贪心直觉: 负的前缀只会拖累后面的和, 不如不要。
//
// 时间复杂度: O(n), 单趟扫描。
// 空间复杂度: O(1), 仅用 cur/ans 两个变量(标准 Kadane 已是空间下界; 滚动数组天然无需额外数组)。
// 是否理论下界: 是。每个元素至少要看一次才能确定最大和, Ω(n) 是信息论下界, Kadane 已达到。
//
// 【面试官常追问的坑】
//   - 初始化不能写 cur, ans = 0, 0: 当数组全为负数(如 [-1,-2,-3])时, 0 会比所有真实子数组和都大,
//     返回 0 是错的(题目要求至少选一个元素, 应返回最大的那个负数 -1)。所以必须用 nums[0] 初始化,
//     即"假设第一个元素就是答案"作为起点。这是全负用例能否通过的关键。
//   - 必须先更新 cur 再更新 ans, 且 ans 要在每轮循环里都更新(不能最后才取 max)——
//     因为最大和可能落在数组任意位置, 不一定是最后一个 cur。
//   - 空数组返回 0 是题目约定之外的边界, 这里按"无元素则和为 0"处理; LeetCode 保证 nums 非空,
//     保留这层防御不影响主逻辑, 但要注意不同题面(如允许空子数组)对空输入的语义可能不同。
//   - 若题面改为"允许空子数组(和为 0)"，只需把 ans 初始化成 0 即可——全负数组此时应返回 0 而非最大负数。
func maxSubArray(nums []int) int {
	if len(nums) == 0 {
		return 0
	}
	// 用 nums[0] 同时初始化 cur 和 ans:
	// cur 表示"以 nums[0] 结尾的最大和", 自然就是 nums[0] 本身;
	// ans 作为全局最大, 当前也只有一个元素可选, 故同为 nums[0]。
	// 【易错】若写成 0, 全负数组会错误返回 0; 见上方注释。
	cur, ans := nums[0], nums[0] // cur=以当前元素结尾的最大和,ans=全局最大
	for i := 1; i < len(nums); i++ {
		// 状态转移: 以 i 结尾的最大和 = max(接在前面那段后面, 单独从 i 起头)。
		// cur+nums[i]: 前面那段以 i-1 结尾的最大和 + 当前元素, 即"延续前段"。
		// nums[i]:     抛弃前面累积(因其为负贡献), 从 i 重新开始。
		// 【WHY 不是 max(cur, nums[i])】必须把 nums[i] 加到 cur 上再比较,
		//   因为"以 i 结尾"的子数组必然包含 nums[i], 不能丢掉它; 只比较 cur 会让负的 nums[i]
		//   错误地保留旧前缀, 得到的不是"以 i 结尾"的和。
		cur = max(cur+nums[i], nums[i]) // 延续前段 或 从 i 重新开始
		// 全局答案取所有位置 cur 的最大值; 必须每轮都更新, 因为最优解未必出现在末尾。
		ans = max(ans, cur)
	}
	return ans
}
