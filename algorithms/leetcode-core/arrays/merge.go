package arrays

// 合并两个有序数组
// https://leetcode.cn/problems/merge-sorted-array/description/
//
// 题意:
//   nums1 长度为 m+n, 前 m 个是有效元素, 后 n 个是 0(占位); nums2 长度为 n。
//   要求把 nums2 合并进 nums1, 使 nums1 成为长度 m+n 的升序数组。要求原地修改。
//
// 算法选择 —— 为什么选"从后往前"双指针而不是"从前往后":
//   1) 题目保证 nums1 尾部预留了 n 个空位, 从尾部往前填, 不会覆盖 nums1 中尚未处理的元素。
//      若从前往后放, nums1 的有效元素会被自己写出的结果覆盖, 必须额外开 O(m+n) 辅助数组,
//      这就破坏了"原地"的要求。
//   2) 从后往前相当于"倒序归并": 每次取两段当前末尾的较大者放到 ans 末尾,
//      和归并排序 merge 阶段完全对称, 只是把方向反过来。
//   3) 时间 O(m+n), 空间 O(1)。空间已经是理论下界(原地), 时间也是下界
//      (每个元素至少要被写入一次, Ω(m+n))。
//
// 易错点/面试追问:
//   - 【方向】必须从尾部填, 从头部填会踩自己未读的数据。
//   - 【循环条件 m > 0 && n > 0】只有两个源段都还有元素时才比较;
//     退出后只需处理 nums2 的剩余(见下)。
//   - 【为什么不用处理 nums1 的剩余】nums1 的剩余元素本来就在它该在的位置上:
//     假设循环退出时 m > 0、n == 0, 说明 nums2 已全部归位, 而 nums1 前 m 个元素
//     本就处于数组最前 m 个位置, 无需移动。这是"从后往前"写法独有的省事点。
//   - 【为什么必须处理 nums2 的剩余】nums2 的元素还在另一个数组里, 没搬过来, 必须显式 copy。
//   - 【比较用 >= 而不是 >】用 >= 把相等的元素先放 nums2 的, 对稳定性无影响(本题不要求稳定),
//     但写成 >= 或 > 都正确, 这里取 >= 与"归并取较大放末尾"的直觉一致。
//   - 【空数组边界】m==0 或 n==0 时, 循环不进, 走 copy 分支或直接跳过, 行为正确。
func merge(nums1 []int, m int, nums2 []int, n int) {
	// 合并后数组的总长度, 作为写入位置 i 的起点
	totalLen := m + n

	// i 指向当前要填的"末尾空位", 每轮递减。
	// 循环条件 m > 0 && n > 0: 两段都还有元素时才需要比较取较大者;
	// 一旦某段耗尽就退出, 剩余段单独处理(见下方)。
	for i := totalLen - 1; m > 0 && n > 0; i-- {
		// 注意下标是 m-1 / n-1: m、n 表示"剩余元素个数", 而非下标。
		// 容易写错成 nums1[m]、nums2[n] 导致越界。
		num1 := nums1[m-1]
		num2 := nums2[n-1]

		// 取两段末尾的较大者放到 ans 末尾。
		// 放哪段就把哪段的"剩余计数"减一(等价于指针前移)。
		// 【坑】这里只动一个指针, 不要同时动; 放 nums2 时减 n, 放 nums1 时减 m。
		if num2 >= num1 {
			nums1[i] = num2
			n--
		} else {
			nums1[i] = num1
			m--
		}
	}

	// 循环退出后只可能是两种情况:
	//   (a) n == 0: nums2 已全部归位, nums1 前 m 个本来就对, 不用动 —— 不进 if。
	//   (b) m == 0 且 n > 0: nums2 还有 n 个更小的元素没搬, 需要把它们放到 nums1 最前面。
	// 【坑】只补 nums2 的剩余, 不补 nums1 的剩余(原因见上方说明), 这是这个写法能 O(1) 空间的关键。
	if n > 0 {
		copy(nums1[:n], nums2[:n])
	}
}
