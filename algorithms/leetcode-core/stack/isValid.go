package leetcode

// 有效的括号
// https://leetcode.cn/problems/valid-parentheses/description/

// isValid 判断字符串中的括号是否合法匹配。
//
// 题意: 字符串只含 '(', ')', '{', '}', '[', ']'，判断所有括号是否正确闭合，
//   即每个闭括号必须与最近一个未匹配的开括号类型相同，且最终没有残留开括号。
//
// 算法选择: 栈。
//   - 为什么用栈: 括号匹配本质是"后进先出"——最后出现的开括号必须最先被关闭。
//     这种 LIFO 结构恰好对应栈语义，所以是天然适配。
//   - 为什么不用计数器(比如只统计左括号数量): 计数器无法区分类型。
//     例如 "([)]" 计数 left==0 但类型错配，计数法无法识别，必须存"具体是哪种开括号"。
//   - 为什么不用递归/DP: 本题没有嵌套层数的约束，递归会退化为对每个字符的判断，
//     既无收益又增加栈溢出风险；DP 更是大材小用。
//   - 一次遍历即可，无需回溯或多次扫描。
//
// 复杂度:
//   - 时间 O(n): 每个字符最多入栈、出栈各一次。
//   - 空间 O(n): 最坏情况全是开括号 "((((..."，栈存 n 个元素。
//     这是理论下界——必须至少记录所有未闭合的开括号，无法做到 O(1)。
//
// 易错点(面试官常追问):
//   1) 闭括号到来时栈空 -> 直接 false，不能误判为合法(如 ")" 应非法)。
//   2) 最终必须检查栈是否为空，"(" 这种残留开括号也属非法。
//   3) 用 map 把闭括号映射到对应开括号是关键技巧: 避免冗长的 if-else 链，
//      同时让"判断是开还是闭"与"取出期望匹配"合为一步。
func isValid(s string) bool {
	// 闭括号 -> 期望匹配的开括号。只列闭括号作为 key，开括号不进 map，
	// 这样用 `_, ok := pairs[c]` 就能区分开/闭: ok 为真说明 c 是闭括号。
	// 【坑】不要把开括号也放进 map，否则无法用 ok 区分开闭两类。
	pairs := map[byte]byte{')': '(', ']': '[', '}': '{'}

	// 用 slice 模拟栈。Go 没有内置栈，slice + 尾部增删 即可。
	// 【面试点】也可用 container/list 或用固定数组+top 指针，但 slice 更简洁、
	//   且本题 n 不大，slice 扩容代价可忽略。
	var stack []byte

	for i := 0; i < len(s); i++ {
		c := s[i]
		if open, ok := pairs[c]; ok {
			// c 是闭括号: 栈顶必须正好是它对应的开括号。
			// 【坑1】先判栈空再取栈顶，否则 stack[len-1] 会越界 panic。
			//   顺序不能反: `stack[top] != open || len==0` 这样写，短路求值失效会 panic。
			// 【坑2】必须类型严格相等，"(" 不能匹配 "]"，所以不能只看数量。
			if len(stack) == 0 || stack[len(stack)-1] != open {
				return false
			}
			// 出栈: 切片缩尾即可，无需显式置零(底层会 GC 回收)。
			stack = stack[:len(stack)-1]
		} else {
			// c 是开括号: 直接入栈，延迟到对应的闭括号来时再匹配。
			// 不在这里做任何合法性判断——开括号本身永远"暂时合法"，是否非法要等后续闭括号或最终栈空检查来定。
			stack = append(stack, c)
		}
	}
	// 【坑3】必须检查栈空: 若还有未闭合的开括号残留(如 "(((")，前面循环不会 return false，
	//   只有这里能拦住。栈空说明所有开括号都被正确闭合了。
	return len(stack) == 0
}
