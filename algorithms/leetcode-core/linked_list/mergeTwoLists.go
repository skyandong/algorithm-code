package linkedlist

// mergeTwoLists 将两个升序链表合并为一个新的升序链表并返回头节点。
//
// 题意：输入 list1、list2 均已按升序排列，要求返回合并后的升序链表，
//       且需"原地"复用原节点（不新建节点存数据），保持稳定顺序（相等时 list1 在前）。
//
// 算法选择理由：
//   - 此处采用「迭代 + 哑节点（dummy head）」方案。两链表已有序，只需双指针同步推进，
//     每次取较小者接到结果尾部，时间 O(n+m)，空间 O(1)（仅多一个 dummy 节点，常数级）。
//   - 为何不递归？递归写法更短，但深度最坏为 n+m，链表很长时可能触发栈溢出；
//     且面试官常借递归版追问"递归深度是多少、能否改迭代"。迭代版更稳，是首选。
//   - 为何不用额外数组暂存再重排？那样空间 O(n+m)，且要重建链表，多此一举。
//
// 复杂度是否为下界：
//   - 时间 O(n+m)：每个节点至少要被访问一次才能比较并接入，无法低于线性，已是最优。
//   - 空间 O(1)：未使用额外与输入规模相关的存储，已是理论下界。
//
// 【哑节点（dummy head）是本题最关键的技巧】
// 不用哑节点时，第一个接入的节点需要单独处理（因为没有"前驱"可接），代码要写一段
// if list1.Val <= list2.Val { head = list1; ... } else { head = list2; ... } 的特判，
// 既冗长又易错。引入 dummy 后，所有节点（含第一个）都用统一逻辑 cur.Next = xxx 接入，
// 最后返回 head.Next 即可。这是链表题通用套路：凡是"结果链表头一开始不确定/需特判"的题
// （合并、删除、分区等），优先用哑节点消除特判。
func mergeTwoLists(list1 *ListNode, list2 *ListNode) *ListNode {
	// head 是哑节点（哨兵），其 Val 不参与结果，仅为简化首节点接入逻辑而存在。
	// cur 始终指向"结果链表的当前末尾"，即下一个待接入节点的前驱。
	// 注意：cur 与 head 初始指向同一个 dummy，之后 cur 逐步后移，head 始终留在原地用于最终返回。
	head := new(ListNode)
	cur := head

	// 只有两条链都还有节点时才需要比较；一旦一方耗尽，另一方整体已有序，直接整段接上即可，
	// 不必再逐个比较（这是 O(n+m) 而非退化成更差的循环的关键）。
	for list1 != nil && list2 != nil {
		// 等号取 <= 而非 <：保证相等时优先取 list1 的节点，从而合并结果是"稳定"的
		// （list1 中靠前出现的元素在结果中仍靠前）。本题不强制稳定，但稳定写法更通用、
		// 在「合并 K 个有序链表 / 归并排序链表」等衍生题里可避免不必要的跨链重排。
		if list1.Val <= list2.Val {
			cur.Next = list1
			list1 = list1.Next
		} else if list2.Val < list1.Val {
			// 【易错点 / 可写法】这里的 else if 条件 list2.Val < list1.Val
			// 与外层 if 的条件 list1.Val <= list2.Val 互为补集，因此此处其实就是 else。
			// 写成 else if 在语义上等价，但可读性略差；标准写法直接写 else 即可。
			// 不改逻辑、仅作说明：当前写法正确，仅风格上偏啰嗦。
			cur.Next = list2
			list2 = list2.Next
		}
		// 无论从哪条链取节点，cur 都要后移一格，指向新的末尾。
		// 【常见坑】漏写这一行会导致所有节点都接到 cur.Next 同一位置，结果只剩最后一个节点。
		cur = cur.Next
	}

	// 循环结束时必有一方为 nil。把另一方"剩余整段"直接挂到 cur.Next 上即可，
	// 无需逐节点复制——因为剩余段本身已是有序链表，整段拼接后整体仍有序。
	// 两个 if 而非 if/else：至多一方非空，二者互斥但都用 if 写更直白，效果一致。
	if list1 != nil {
		cur.Next = list1
	}
	if list2 != nil {
		cur.Next = list2
	}
	// 跳过哑节点返回真正的头。当 list1、list2 同时为 nil 时，head.Next 为 nil，
	// 自然返回空链表，无需对"两边都空"做额外特判——哑节点已统一处理。
	return head.Next
}
