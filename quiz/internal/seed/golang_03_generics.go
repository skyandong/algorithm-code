// golangGenerics 出题范围：notes/golang/03-泛型.md
// 出题规范：答案位置在本文件内均衡分布；干扰项须与正确项长度相当，
// 每个干扰项绑定一个具体误区；解析用 A/B/C/D 引用选项，不写「第N项」。
func golangGenerics() []model.Question {
	t := topic{
		module: "golang",
		slug:   "golang-03",
		name:   "泛型",
		source: "notes/golang/03-泛型.md",
	}
	q := t.builder()

	return []model.Question{
		q("泛型要解决的「interface 的结构性缺陷」主要指什么？",
			[]string{
				"接口不能有多个实现，一个接口只能绑定到一个具体类型上",
				"接口表达不了方法以外的约束，值类型装进接口还要装箱与断言",
				"接口的方法调用在编译期无法确定，必须等到链接期才能绑定",
				"接口不能被嵌入到结构体里，导致组合式设计完全用不上",
			}, 1,
			"用 any 写通用容器，一是约束表达不出来（编译器不知道能不能比较、能不能排序），"+
				"二是每次存取都要装箱和断言，值类型还要额外分配。泛型把类型参数化，约束写在编译期，值类型零装箱。"+
				"A、D 与接口的能力不符：接口可以有任意多个实现，也允许嵌入。"+
				"C 说反了——接口调用确实是运行期分发，但那不是「缺陷」本身，缺陷是它带来的开销与约束缺失。"),

		q("关于 `~int` 这类近似约束，下列说法正确的是？",
			[]string{
				"匹配所有能转换成 int 的类型，float64、rune 这类都算在内",
				"与不带波浪号的 int 完全等价，只是多一种可选写法",
				"表示该类型参数可以取任意类型，本质是 any 的语法糖",
				"匹配所有底层类型为 int 的类型，比如自定义的 type UserID int 也能通过",
			}, 3,
			"带 ~ 的约束看的是底层类型，所以基于 int 定义的新类型也满足。"+
				"A 把「可转换」当成了「底层类型相同」，float64 的底层类型是它自己。"+
				"B 忽略了关键差别：不带 ~ 时只匹配 int 本身，UserID 会被拒之门外。C 那是 any 的含义。"+
				"要注意的代价是：~int 的集合里没法再按方法区分成员，需要方法就得定义更精确的约束。"),

		q("comparable 约束的精确语义是什么？",
			[]string{
				"「== 可用且不 panic」的类型集合，slice、map、函数根本不满足",
				"所有类型都能满足 comparable，只是有些类型在比较的时候会 panic 而已",
				"只有数值类型满足 comparable，string 和指针都不行",
				"满足 comparable 的类型既能做 map 的 key，也一定可以拿来排序",
			}, 0,
			"comparable 描述的是可比较性，slice、map、函数只能与 nil 比，所以被排除在外；"+
				"struct 是否可比取决于字段是否全部可比，所以是「纯值 struct」。"+
				"B 与事实不符——不可比较的类型根本进不了这个约束。C 窄得离谱，string 就可比。"+
				"D 混进了另一件事：能算相等不代表能比大小，排序需要 cmp.Ordered 这类约束。"),

		q("为什么 Go 的方法不能带自己的类型参数？",
			[]string{
				"因为方法里的类型参数无法从调用处推断出来，编译器实现起来过于困难",
				"因为方法参数已经够用了，语言设计者认为不需要再加一层参数",
				"方法级类型参数会让接口满足性检查不可判定：说不清要实现多少个方法才算实现接口",
				"因为反射拿不到方法上的类型参数，运行期会丢失这部分信息",
			}, 2,
			"同一个方法名配任意类型参数会展开成无穷多组签名，接口定义里没法把「实现」说清楚，所以语言层面直接禁止。"+
				"绕法是写包级泛型函数，标准库的 slices 包全是这个风格——slices.SortFunc(xs, cmp) 而不是 xs.SortFunc(cmp)。"+
				"A、D 把设计决策说成了实现偷懒。B 不是原因，够不够用跟能不能有是两回事。"),

		q("Go 泛型的实现机制是什么？",
			[]string{
				"对每个具体类型都完整展开一份机器码，与 C++ 模板的全量展开做法一致",
				"与 Java 一样做类型擦除，运行期拿不到任何类型信息",
				"完全靠反射在运行期解释执行类型参数相关的操作",
				"按内存布局分组（GC shape）：布局相同的类型共享机器码，组内差异靠编译期字典传递",
			}, 3,
			"所有指针类型的内存布局相同，可以共用一份代码，组内的类型元数据、操作函数、方法入口"+
				"打包成字典在调用时传进去。A 是 C++ 的全量展开，代码膨胀严重，Go 明确不走这条路。"+
				"B 是类型擦除，那样值类型就得装箱，也拿不到类型信息。C 与实现不符，泛型是编译期机制。"),

		q("泛型与接口该怎么选？",
			[]string{
				"泛型在编译期展开、性能总是更好，所以任何场景都一律优先选泛型",
				"类型维度用泛型（容器、工具函数）；行为维度用接口（多态、依赖注入、mock）",
				"接口更通用也更灵活，新的项目里应该一律改用接口",
				"两者语义冲突，不能共存于同一个项目甚至同一个包",
			}, 1,
			"判据是「变化的维度」：类型维度用泛型，行为维度用接口。"+
				"而且两者能组合：泛型结构体里放一个接口字段，类型参数管布局，接口管行为。"+
				"A 忽略了泛型的约束能力有限，运行时多态表达不出来。C 放弃了泛型的编译期约束与零装箱。"+
				"D 与事实相反，组合用法很常见。"),

		q("泛型一定比接口快吗？",
			[]string{
				"一定更快，因为省掉了接口分发的间接跳转和运行期断言",
				"一定更慢，因为每次调用都要多做一次字典查找，还有额外间接开销",
				"通常不慢但别想当然：省了装箱，字典间接又让部分内联失效，需 benchmark",
				"两者性能完全一致，编译器会把接口调用优化成等价的泛型调用",
			}, 2,
			"省装箱是确定收益（值类型不再为了装 any 而逃逸到堆上），但字典间接跳转与内联失效是确定代价，"+
				"谁占上风取决于具体代码。A、B 把结论说死，都只看到一半。D 没有这种优化。"+
				"结论是能用 benchmark 验证的，别凭感觉选。"),

		q("标准库的 slices 包为什么提供 SortFunc 这样的函数，而不是定义在切片类型上的方法？",
			[]string{
				"因为 Go 不允许方法带自己的类型参数，SortFunc 需要的元素类型参数只能放到包级函数上",
				"因为包级函数比方法的调用路径更短，性能上有肉眼可见的优势，标准库很在意",
				"因为方法的接收者不能是切片类型，语言层面禁止了这种定义，写了就报错",
				"因为函数式风格更加现代，标准库想借这些 API 倡导这种写法，与语言限制无关",
			}, 0,
			"SortFunc 需要再引入一个元素类型的参数，方法级类型参数被语言禁止，"+
				"所以只能写成 slices.SortFunc(xs, cmp) 这种包级函数。B 性能不是原因。"+
				"C 说错了，切片可以做接收者。D 是风格偏好，不是语言限制导致的结果。"),

		q("用泛型写容器时，声明元素零值的标准写法是什么？",
			[]string{
				"用 nil 即可，它对任何类型参数都成立",
				"用 reflect.Zero(reflect.TypeOf(x)) 在运行期取零值",
				"泛型类型参数没有零值概念，必须要求约束里自带构造方法",
				"var zero T 直接声明即可；需要指针型的零值时用 new(T) 拿到已置零的指针",
			}, 3,
			"var zero T 对任何类型参数都合法，值类型得到数值零值、指针与接口得到 nil。"+
				"A 对值类型不成立，nil 不能赋给 int。B 能用但绕远路，运行期反射完全没有必要。"+
				"C 凭空加限制，Go 的零值机制对类型参数一样有效。"),

		q("类型参数能不能被自动推断出来？",
			[]string{
				"不能，任何泛型函数调用都必须写全方括号里的类型参数",
				"能：实参足以确定类型参数就可省略方括号，推不出来才显式实例化",
				"只能推断与返回值相关的类型参数，入参类型必须手写",
				"推断只在同一个包内有效，跨包调用必须显式实例化",
			}, 1,
			"类型推断看的是实参，能从函数参数确定就省略，确定不了就得手写。"+
				"A 过严，日常调用绝大多数都不用写方括号。C 与规则不符，推断只看参数不看返回值。"+
				"D 没有这条限制，推断与包边界无关。"),
	}
}
