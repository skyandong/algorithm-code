package seed

import "quiz/internal/model"

// golangInterface 出题范围：notes/golang/02-interface与反射.md
// 出题规范：答案位置在本文件内均衡分布；干扰项须与正确项长度相当，
// 每个干扰项绑定一个具体误区；解析用 A/B/C/D 引用选项，不写「第N项」。
func golangInterface() []model.Question {
	t := topic{
		module: "golang",
		slug:   "golang-02",
		name:   "interface 与反射",
		source: "notes/golang/02-interface与反射.md",
	}
	q := t.builder()

	return []model.Question{
		q("空接口 any 与非空接口的底层表示有什么区别？",
			[]string{
				"两者完全一样，都是 (类型, 值) 二元组，空接口只是恰好没有方法的特例",
				"空接口只有数据指针，类型信息编码在数据块自己的头部里",
				"空接口是 (类型, 值) 二元组；非空接口是 (itab, 值)，itab 含方法表",
				"非空接口存的是接口名与实现类型名两个字符串，运行期靠名字查表做分发",
			}, 2,
			"空接口 eface 只有类型指针与数据指针；非空接口 iface 把类型指针换成了 itab 指针，"+
				"itab 里装着动态类型和该类型实现这个接口的方法表。A 抹掉了这层差别——有没有方法表直接决定接口调用怎么分发。"+
				"B 错在类型信息必须单独存在头的字段里，数据里看不出来。"+
				"D 把运行期的指针分发说成了按名字查找，与实际实现不符。"),

		q("代码：var p *T = nil，然后 var i any = p。此时 i == nil 的结果是什么？",
			[]string{
				"false：动态类型是 *T、动态值是 nil，有类型无值不算 nil 接口",
				"true：接口判空只看数据指针这一个字段，底层指针是空的接口就是空的",
				"编译不通过：nil 的具体指针不允许赋给 any 类型的变量",
				"运行期 panic：== 比较时解引用了空指针",
			}, 0,
			"接口判空看的是「类型与值是否都为 nil」，这里类型是 *T，所以接口本身不为 nil。"+
				"这是线上事故的常见来源：函数返回一个 nil 的具体指针，被赋给 error 接口后就不再等于 nil。"+
				"B 只看了值那一半。C 语法完全允许这种赋值。D 判空不做解引用。"+
				"要正确判空用 reflect.ValueOf(i).IsNil()，或者先断言成具体类型再判。"),

		q("关于 T 与 *T 的方法集，下列说法正确的是？",
			[]string{
				"T 与 *T 的方法集完全相同，区别只在于调用时接收者的书写形式不同，不影响接口满足性的判断",
				"T 的方法集反而更大，因为 T 总能自动取地址变成 *T 去调用指针方法，实现接口时更方便",
				"指针方法能被 T 的值直接调用，所以 T 的方法集同样包含指针方法，把 T 的值存进接口后也满足接口约束",
				"*T 的方法集包含值方法与指针方法，T 只有值方法；*T 实现了某个接口，不代表 T 也实现了",
			}, 3,
			"方法集是类型层面的规则：*T 才包含指针方法。A 忽略了这条差别。"+
				"B 把方法集和可寻址性搅在一起。C 是关键误区：T 在可寻址的条件下确实能调用指针方法（编译器自动取址），"+
				"但把 T 的值存进接口时可能不可寻址，编译器没法替你取址，方法集里就没有这些方法。"+
				"实践中接口如果声明了指针方法，就统一用 *T 去实现和传递。"),

		q("把一个 int 变量赋给 any，运行期发生了什么？",
			[]string{
				"只存一个指针，值本身不拷贝，接口和原变量共享同一份数据",
				"值拷贝进接口的数据字段；装箱没有小整数缓存，逃逸时就是一次堆分配",
				"装箱是纯寄存器操作，不产生任何堆分配，也不影响逃逸分析的结果",
				"接口里存的是原变量的引用，之后修改原变量会同步改掉接口里的值",
			}, 1,
			"接口的数据字段装的是一份值拷贝，装箱本身不改原变量；编译器判定它逃逸时"+
				"（传给接口、跨 goroutine、被闭包捕获等）就落到堆上。要记的是：热路径上频繁把数值装进 any "+
				"会带来额外分配与间接寻址，泛型能省掉这一层。A、D 都把值语义说成了引用语义。"+
				"C 忽略了逃逸的可能。"),

		q("类型断言 v := i.(T) 与 v, ok := i.(T) 的区别是什么？",
			[]string{
				"前者断言失败会 panic，后者失败时 v 取 T 的零值、ok 为 false",
				"前者失败返回 nil，后者失败返回零值，两者都不会 panic",
				"两者完全等价，ok 只是给读代码的人一个明确的标记",
				"后者在失败时同样会 panic，只是多返回一个 ok 说明失败原因",
			}, 0,
			"单值形式把断言失败当作程序错误，直接 panic；逗号 ok 形式把失败变成可判定的返回值，"+
				"库代码和解析外部输入时都应该用后者。B 把「零值」和「nil」混了，v 的零值取决于 T 是什么。"+
				"C 忽略了 panic 这个实质差别。D 正好说反。"),

		q("在 switch v := i.(type) 里，每个 case 分支中 v 的类型是什么？",
			[]string{
				"整个 switch 里 v 始终保持接口类型，每个分支都要再断言一次",
				"v 的静态类型是 any，分支里要用 reflect 才能拿到具体类型",
				"只能写一个 case 分支，写多个分支会编译报错",
				"每个 case 里 v 就是该分支匹配到的具体类型，可以直接调用它的方法",
			}, 3,
			"type switch 会为每个分支单独确定 v 的静态类型，这也是它比链式断言更好用的原因。"+
				"A、B 都以为 v 还是接口，白白浪费了这层能力。C 与语法不符：分支可以有很多个，还能用 default 兜底。"),

		q("用反射修改一个变量的值，需要满足什么条件？",
			[]string{
				"只要拿到 reflect.Value 就能调用 Set 系列方法，失败只是返回 false",
				"必须借助 unsafe.Pointer 做一层手工转换，才能获得越权写入的能力",
				"Value 必须可寻址——从指针的 Elem() 拿到——并且 CanSet 为真",
				"把变量取址传给 reflect.ValueOf，返回的 Value 就能直接 Set",
			}, 2,
			"reflect.ValueOf(x) 拿到的是一份不可寻址的副本，对它 Set 直接 panic；"+
				"要改就传 &x，再用 Elem() 拿到指针指向的那个可寻址值，此时 CanSet 才为真。"+
				"A 忽略了可寻址性这道门。B 用不上 unsafe，这是反射的标准能力。"+
				"D 漏了关键的 Elem() 一步——传指针只是第一步，那个 Value 本身代表的是指针。"),

		q("反射为什么慢？工程上应该怎么用？",
			[]string{
				"反射与直接调用开销相当，编译器优化之后可以放心用在热路径上",
				"类型判断、接口转换、可寻址性检查都在运行期做且无法内联；边界解析一次并缓存，热路径直接调用",
				"只有 ValueOf 这一步慢，Set 和 Field 都很快，所以随意组合也没问题",
				"把 reflect.Value 存进 map 里复用，就能自动加速所有反射操作",
			}, 1,
			"反射把编译期能定的事推到运行期，还挡住了内联，调用链越长越贵。"+
				"常见做法是只在配置解析、序列化入口、依赖注入这类边界上用反射，解析完把结构信息或生成的函数存起来复用。"+
				"A 与实测不符。C 把开销来源归错了对象。D 的缓存要有意义，得缓存解析后的调用路径或生成的代码，"+
				"缓存 Value 本身解决不了运行期判断的问题。"),

		q("两个接口值用 == 比较，什么时候相等、什么时候 panic？",
			[]string{
				"只要动态类型相同就相等，动态值不需要参与比较",
				"接口永远不能用 == 比较，必须换成 reflect.DeepEqual",
				"接口比较只看数据指针是否指向同一处地址，指向同一处才算相等",
				"动态类型相同且动态值相等才相等；动态值是不可比较类型（slice）时 panic",
			}, 3,
			"接口比较是两步：先比动态类型，类型不同直接不等；类型相同再比值本身。"+
				"类型层面接口是可比较的，所以「动态值不可比较」这件事编译器拦不住，只能在运行期 panic。"+
				"A 漏了值的比较。B 太绝对，接口用 == 是合法的。C 把值语义说成了指针语义——两个内容相同的副本也相等。"),

		q("把一个具体类型的值赋给接口，运行期这次「类型 × 接口 → itab」的查找开销有多大？",
			[]string{
				"每次赋值都要重新计算一遍 itab，所以接口方法调用的代价恒定在高位下不来",
				"itab 在编译期就完全确定并内联进代码，运行期零开销",
				"有全局缓存：同一组（类型, 接口）只算一次 itab，之后接口调用只是间接跳转",
				"只有接口的方法数超过一定阈值才会生成 itab，小接口直接比较函数指针",
			}, 2,
			"itab 是算一次、缓存起来复用的，所以接口分发的常态成本接近一次间接跳转，比很多人想象的便宜。"+
				"A 把一次性成本说成了每次成本。B 漏掉了动态类型必须等运行期才知道这一事实。D 没有这条规则。"),
	}
}
