// # 高可用
//
// Redis 高可用有三个层次:主从复制(基础)、哨兵(自动故障转移)、集群(水平扩展)。
//
// # 主从复制
//
// 主从同步用 PSYNC 协议,分两种:
//
// 全量同步(第一次连接或 repl_backlog 不够用时):
//
//	slave 发 PSYNC ? -1
//	master 执行 bgsave 生成 RDB 发给 slave
//	发送期间的新命令缓存在 replication buffer
//	slave 加载 RDB 后接收并执行缓存命令
//
// 部分重同步(断线重连,offset 在 backlog 内):
//
//	slave 发 PSYNC <replid> <offset>
//	master 从 repl_backlog 里找到 offset 位置,只补发差异
//
// 关键参数:
//
//	repl-backlog-size   默认 1MB,断线时间长或写量大需要调大
//	                    backlog 不够 → 降级为全量同步 → 性能抖动
//
// 复制是异步的:master 不等 slave 确认就返回客户端,所以 slave 数据可能落后。
//
// # 哨兵(Sentinel)
//
// 哨兵解决的问题:master 宕机时自动完成故障转移,不需要人工干预。
//
// 哨兵的四个职责:
//
//  1. 监控:定期 PING master/slave/其他哨兵
//  2. 通知:节点状态变化时通知客户端和管理员
//  3. 自动故障转移:master 下线后选出新 master
//  4. 配置中心:客户端通过哨兵获取当前 master 地址
//
// 故障转移流程:
//
//	单个哨兵认为 master 不可达 → 主观下线(SDOWN)
//	quorum 个哨兵达成一致     → 客观下线(ODOWN)
//	哨兵之间选举 Leader(Raft) → Leader 执行故障转移
//	选最优 slave 提升为新 master(优先级、复制偏移量、runid)
//	通知其他 slave 切换复制源
//	通知客户端新 master 地址
//
// 数据丢失的两种场景:
//
//  1. 异步复制丢失:master 写入但未同步到 slave 就宕机
//  2. 脑裂丢失:master 假死,客户端继续写入孤立 master,
//     哨兵切换完成后孤立 master 以 slave 身份回归,数据被覆盖
//
// 防脑裂配置:
//
//	min-replicas-to-write 1    至少 1 个 slave 确认才接受写入
//	min-replicas-max-lag  10   slave 超过 10 秒没响应则拒绝写入
//
// 代价:可用性略降(没有 slave 时 master 拒绝写),但防止了脑裂丢数据。
//
// # 集群(Cluster)
//
// 集群解决的问题:单机内存上限和写入瓶颈,实现水平扩展。
//
// 哈希槽:
//
//	共 16384 个槽,每个 key 通过 CRC16(key) % 16384 映射到槽
//	每个节点负责一部分槽,数据随槽分布在各节点
//
// 为什么是 16384 不是 65536(CRC16 的全部范围):
//
//  1. 心跳包体积:每个节点心跳包含槽位 bitmap
//     65536 槽 → bitmap = 8KB,太大
//     16384 槽 → bitmap = 2KB,合适
//  2. 集群规模上限约 1000 节点,16384/1000 ≈ 16 槽/节点,粒度够用
//     (antirez 在 GitHub issue #2576 中亲自解释)
//
// 为什么不用一致性哈希:
//
//	一致性哈希         哈希槽
//	节点负责一段弧     节点负责固定数量的槽
//	扩容时自动均衡     扩容时手动指定迁移哪些槽
//	迁移范围不可控     迁移范围精确可控
//	数据分布不均匀     数据分布更均匀(槽粒度细)
//	虚拟节点解决均匀   不需要虚拟节点
//
// 哈希槽的核心优势:扩缩容时能精确控制迁移哪些槽到哪些节点,
// 运维人员可以根据节点容量手动调配,比一致性哈希的自动均衡更可控。
// 一致性哈希的弧段划分天然不均匀,需要虚拟节点补偿,实现更复杂。
//
// 扩缩容时的槽迁移响应:
//
//	ASK    槽正在迁移中,key 可能在目标节点(临时重定向,客户端不更新路由表)
//	MOVED  槽已永久迁移到新节点(客户端应更新本地槽映射)
//
// 集群限制:
//
//   - 多 key 操作(MGET/MSET/事务/Lua)要求所有 key 在同一槽
//     解决:hash tag,用 {} 指定参与哈希的部分
//     {user:1000}:profile 和 {user:1000}:order 落同槽
//   - 不支持跨槽的 db select(集群只有 db0)
//   - 批量操作需要客户端自己按槽分组
//
// # Codis(了解即可,已被抛弃)
//
// 背景:Redis 官方集群 3.0(2015年)才发布,Codis 是豌豆荚在此之前造的代理式分片方案(2014年开源)。
//
// 架构:
//
//	客户端 → Codis Proxy(路由层) → Codis Server(魔改版 Redis)
//	                ↓
//	         ZooKeeper/etcd(存槽位元数据)
//
// 优点(当时):客户端无需改造,从单机迁移透明;国内大厂生产验证过。
//
// 为什么被抛弃:
//
//   - Proxy 多一跳,延迟增加
//   - Codis Server 是魔改版 Redis,跟不上官方版本,安全补丁和新特性都滞后
//   - 依赖 ZooKeeper/etcd,架构更复杂,运维成本高
//   - CodisLabs 团队解散后基本停止维护(2019年后几乎无更新)
//
// 面试答法:Codis 是官方集群成熟前的过渡方案,代理层透明路由是其核心。
// 官方集群稳定后被替代,新项目不应选用。
//
// # 主从 vs 哨兵 vs 集群 选型
//
//	主从        读写分离,无自动故障转移,适合读多写少且能接受手动切换
//	哨兵        自动故障转移,适合需要高可用但数据量单机能装下
//	集群        数据量超单机上限或写入 QPS 超单机瓶颈时才上
//	            集群带来的复杂性(槽迁移、hash tag、客户端改造)不可忽视

